"""Synthetic datasets with known ground-truth coefficients.

Both datasets are generated from a stated linear model plus Gaussian
noise, so the *true* coefficients are known exactly and solver
recovery can be measured against them (not just against the other
solver). Everything is seeded through ``numpy.random.default_rng``,
so every run of this project — the CLI, the tests, the committed
example outputs — sees byte-identical data.

The multivariate dataset is dressed up as a house-price problem
(size / rooms / age -> price) purely as readable labels. It is
synthetic, generated by this file, and labelled as such everywhere
it appears. Its features deliberately span very different scales
(rooms ~ 1-6, age ~ 0-40 years, size ~ 30-200 m^2), which is what
makes feature standardisation matter for gradient descent.
"""

from __future__ import annotations

import numpy as np

# Ground-truth models. beta[0] is the intercept.
UNIVARIATE_BETA = np.array([2.0, 3.0])            # y = 2 + 3*x
UNIVARIATE_NOISE = 1.5
MULTIVARIATE_BETA = np.array([50.0, 2.5, 8.0, -1.2])
MULTIVARIATE_NOISE = 12.0
FEATURE_NAMES = ["size_m2", "rooms", "age_years"]
TARGET_NAME = "price_k"


def make_univariate(n: int = 120, seed: int = 42) -> dict:
    """One feature, x ~ U(0, 10); y = 2 + 3x + N(0, 1.5^2)."""
    rng = np.random.default_rng(seed)
    x = rng.uniform(0.0, 10.0, size=n)
    y = UNIVARIATE_BETA[0] + UNIVARIATE_BETA[1] * x
    y = y + rng.normal(0.0, UNIVARIATE_NOISE, size=n)
    return {
        "X": x.reshape(-1, 1),
        "y": y,
        "beta_true": UNIVARIATE_BETA.copy(),
        "feature_names": ["x"],
        "noise_std": UNIVARIATE_NOISE,
    }


def make_multivariate(n: int = 240, seed: int = 7) -> dict:
    """Three mixed-scale features; y = 50 + 2.5*size + 8*rooms - 1.2*age + N(0, 12^2).

    Rooms is generated *from* size (bigger houses have more rooms,
    as in real housing data), so the two columns are strongly
    correlated. That correlation — not the raw scales, which
    standardisation removes — is what makes the standardised
    problem genuinely ill-conditioned and gives gradient descent a
    real convergence curve to trace.
    """
    rng = np.random.default_rng(seed)
    size = rng.uniform(30.0, 200.0, size=n)        # m^2
    rooms = np.clip(np.round(size / 30.0
                             + rng.normal(0.0, 0.5, size=n)), 1, 7)
    age = rng.uniform(0.0, 40.0, size=n)           # years
    X = np.column_stack([size, rooms, age])
    y = MULTIVARIATE_BETA[0] + X @ MULTIVARIATE_BETA[1:]
    y = y + rng.normal(0.0, MULTIVARIATE_NOISE, size=n)
    return {
        "X": X,
        "y": y,
        "beta_true": MULTIVARIATE_BETA.copy(),
        "feature_names": list(FEATURE_NAMES),
        "noise_std": MULTIVARIATE_NOISE,
    }


def train_test_split(X: np.ndarray, y: np.ndarray,
                     test_fraction: float = 0.25, seed: int = 123):
    """Deterministic shuffled split; returns (X_tr, X_te, y_tr, y_te)."""
    rng = np.random.default_rng(seed)
    idx = rng.permutation(len(y))
    n_test = int(round(test_fraction * len(y)))
    te, tr = idx[:n_test], idx[n_test:]
    return X[tr], X[te], y[tr], y[te]


def write_dataset_csv(dataset: dict, path: str) -> None:
    """Write the multivariate dataset to CSV with a header row."""
    header = ",".join(dataset["feature_names"] + [TARGET_NAME])
    rows = np.column_stack([dataset["X"], dataset["y"]])
    np.savetxt(path, rows, delimiter=",", header=header, comments="",
               fmt="%.4f")
